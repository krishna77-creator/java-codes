package com.krishna.prep.day02;

public class SwapNumbers {
    public static void main(String[] args) {
        int a = 5;
        int b = 9;
        System.out.println("Before: " + "a = " + a + ", b = " + b);
        int c = a;
        a = b;
        b = c;
        System.out.println("After: " + "a = " + a + ", b = " + b);

    }
}
